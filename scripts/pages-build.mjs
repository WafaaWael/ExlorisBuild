import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { brotliDecompressSync } from 'node:zlib';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const build = path.join(root, 'Build');
const partsDir = path.join(root, 'data-parts');
const original = path.join(build, 'Build/Build.data.br');
const sha = data => createHash('sha256').update(data).digest('hex');
const mode = process.argv[2];

if (mode === 'split') {
  const data = fs.readFileSync(original);
  const chunkSize = 48 * 1024 * 1024;
  fs.mkdirSync(partsDir, { recursive: true });
  const parts = [];
  for (let offset = 0; offset < data.length; offset += chunkSize) {
    const bytes = data.subarray(offset, offset + chunkSize);
    const name = `data-${String(parts.length).padStart(3, '0')}.part`;
    fs.writeFileSync(path.join(partsDir, name), bytes);
    parts.push({ name, size: bytes.length, sha256: sha(bytes) });
  }
  // Remove only obsolete chunks generated by this script after a smaller rebuild.
  for (const name of fs.readdirSync(partsDir)) {
    if (/^data-\d+\.part$/.test(name) && !parts.some(p => p.name === name)) {
      fs.unlinkSync(path.join(partsDir, name));
    }
  }
  fs.writeFileSync(path.join(partsDir, 'manifest.json'), JSON.stringify({
    size: data.length, sha256: sha(data), parts
  }, null, 2) + '\n');
  console.log(`Prepared ${parts.length} chunks. Original build preserved.`);
} else if (mode === 'site') {
  const manifest = JSON.parse(fs.readFileSync(path.join(partsDir, 'manifest.json'), 'utf8'));
  const buffers = manifest.parts.map(part => {
    if (!/^data-\d+\.part$/.test(part.name)) throw new Error('Invalid chunk name');
    const bytes = fs.readFileSync(path.join(partsDir, part.name));
    if (bytes.length !== part.size || sha(bytes) !== part.sha256) {
      throw new Error(`Damaged chunk: ${part.name}`);
    }
    return bytes;
  });
  const data = Buffer.concat(buffers);
  if (data.length !== manifest.size || sha(data) !== manifest.sha256) {
    throw new Error('Reassembled build failed integrity verification');
  }
  const output = path.join(root, '_site');
  if (fs.existsSync(output)) throw new Error('_site already exists. Move it aside before building again.');
  fs.cpSync(build, output, {
    recursive: true,
    filter: source => !source.endsWith('.br') && path.basename(source) !== '.DS_Store'
  });
  // Pages cannot set Unity's required Content-Encoding: br headers.
  // Publish decoded assets, keeping compressed originals untouched locally.
  const assets = path.join(output, 'Build');
  fs.writeFileSync(path.join(assets, 'Build.data'), brotliDecompressSync(data));
  for (const name of ['Build.framework.js', 'Build.wasm']) {
    fs.writeFileSync(path.join(assets, name),
      brotliDecompressSync(fs.readFileSync(path.join(build, 'Build', name + '.br'))));
  }
  for (const name of ['index.html', 'ServiceWorker.js']) {
    const file = path.join(output, name);
    if (!fs.existsSync(file)) continue;
    let text = fs.readFileSync(file, 'utf8')
      .replaceAll('Build.data.br', 'Build.data')
      .replaceAll('Build.framework.js.br', 'Build.framework.js')
      .replaceAll('Build.wasm.br', 'Build.wasm');
    if (name === 'ServiceWorker.js') {
      text = text.replace(/const cacheName = .*?;/,
        `const cacheName = "Exloris-pages-${manifest.sha256.slice(0, 16)}";`);
    }
    fs.writeFileSync(file, text);
  }
  fs.writeFileSync(path.join(output, '.nojekyll'), '');
  console.log('Verified chunks and generated _site. Publish this folder, not the source Build folder.');
} else {
  throw new Error('Usage: node scripts/pages-build.mjs split|site');
}
